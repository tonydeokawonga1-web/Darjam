/**
 * Builds the Android web bundle.
 *
 *   node scripts/build-mobile.mjs --api-base https://api.example.com
 *   node scripts/build-mobile.mjs --api-base https://api.example.com --ads
 *
 * client/config.js is generated for the native bundle and restored afterwards,
 * so the hosted web app keeps using relative API paths.
 *
 * Ad unit IDs (optional, pass as env vars):
 *   DARJAM_ADMOB_BANNER, DARJAM_ADMOB_INTERSTITIAL, DARJAM_ADMOB_TEST=0
 */
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const CONFIG_PATH = path.join(ROOT, 'client', 'config.js');

const args = process.argv.slice(2);
const getArg = (name) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : null;
};

const apiBase = (getArg('api-base') || process.env.DARJAM_API_BASE || '').replace(/\/+$/, '');
if (!/^https:\/\//.test(apiBase)) {
  console.error('A public HTTPS API base is required: --api-base https://api.example.com');
  process.exit(1);
}

const adsEnabled = args.includes('--ads') || process.env.DARJAM_ADS === '1';
const testMode = process.env.DARJAM_ADMOB_TEST !== '0';
const bannerId = process.env.DARJAM_ADMOB_BANNER || '';
const interstitialId = process.env.DARJAM_ADMOB_INTERSTITIAL || '';

const generated = `/*
 * GENERATED by scripts/build-mobile.mjs — restored after the Android sync.
 */
window.DARJAM_API_BASE = ${JSON.stringify(apiBase)};

window.DARJAM_ADS = {
  enabled: ${adsEnabled},
  testMode: ${testMode},
  bannerId: ${JSON.stringify(bannerId)},
  interstitialId: ${JSON.stringify(interstitialId)},
};
`;

function run(command, commandArgs) {
  const result = spawnSync(command, commandArgs, { cwd: ROOT, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} ${commandArgs.join(' ')} failed`);
}

const original = await readFile(CONFIG_PATH, 'utf8');
try {
  await writeFile(CONFIG_PATH, generated);
  run(process.execPath, ['scripts/sync-vendor.mjs']);
  run(process.execPath, [path.join(ROOT, 'node_modules', '@capacitor', 'cli', 'bin', 'capacitor'), 'sync', 'android']);
  console.log(`\n[darjam] Android web bundle synced (API: ${apiBase}, ads: ${adsEnabled ? 'on' : 'off'})`);
} finally {
  await writeFile(CONFIG_PATH, original);
}
